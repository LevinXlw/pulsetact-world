import {mkdir, writeFile} from 'node:fs/promises';
import {chromium, expect} from '@playwright/test';

const directory = 'output/character-preview';
await mkdir(directory, {recursive: true});
const browser = await chromium.launch({channel: 'chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist']});
const page = await browser.newPage({viewport: {width: 1600, height: 1000}, deviceScaleFactor: 1});
const errors = [], failures = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => {if (message.type() === 'error') errors.push(message.text());});
page.on('response', response => {if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`);});
const base = process.env.WORLD_BASE_URL || 'http://127.0.0.1:5186';
try {
  await page.goto(`${base}/characters`, {waitUntil: 'domcontentloaded'});
  await expect(page.getByText('实时 3D 预览', {exact: true})).toBeVisible({timeout: 90000});
  await page.waitForFunction(() => window.__worldScene?.characterReady === true);
  await page.waitForTimeout(1600);
  await page.screenshot({path: `${directory}/pixiv-front.png`});
  await page.getByRole('button', {name: '面部近景', exact: true}).click();
  await page.waitForTimeout(1200);
  await page.screenshot({path: `${directory}/pixiv-face.png`});
  await page.getByRole('button', {name: '查看全身', exact: true}).click();
  await page.getByRole('button', {name: '侧面', exact: true}).click();
  await page.getByRole('button', {name: '走路', exact: true}).click();
  await page.waitForFunction(() => window.__worldScene?.characterMotion === 'Walk');
  await page.waitForTimeout(1200);
  await page.screenshot({path: `${directory}/pixiv-walk.png`});
  await page.getByRole('button', {name: '跑步', exact: true}).click();
  await page.waitForFunction(() => window.__worldScene?.characterMotion === 'Run');
  await page.waitForTimeout(800);
  await page.screenshot({path: `${directory}/pixiv-run.png`});
  await expect(page.getByRole('button', {name: /Hiyori/})).toBeDisabled();
  const sakurada = page.getByRole('button', {name: /Sakurada/});
  if (await sakurada.isEnabled()) {
    await sakurada.click();
    await expect(page.getByText('实时 3D 预览', {exact: true})).toBeVisible({timeout: 60000});
    await page.getByRole('button', {name: '正面', exact: true}).click();
    await page.waitForTimeout(1500);
    await page.screenshot({path: `${directory}/sakurada-front.png`});
    await page.getByRole('button', {name: '面部近景', exact: true}).click();
    await page.waitForTimeout(1200);
    await page.screenshot({path: `${directory}/sakurada-face.png`});
    await page.getByRole('button', {name: '查看全身', exact: true}).click();
    await page.getByRole('button', {name: '侧面', exact: true}).click();
    await page.getByRole('button', {name: '跑步', exact: true}).click();
    await page.waitForFunction(() => window.__worldScene?.characterMotion === 'Run');
    await page.waitForTimeout(1200);
    await page.screenshot({path: `${directory}/sakurada-run.png`});
    await page.getByRole('button', {name: /白 T/}).click();
    await expect(page.getByText('实时 3D 预览', {exact: true})).toBeVisible();
  }
  await page.getByRole('button', {name: '待机', exact: true}).click();
  await page.getByRole('button', {name: '正面', exact: true}).click();
  await page.setViewportSize({width: 390, height: 844});
  await page.waitForTimeout(1200);
  await page.screenshot({path: `${directory}/mobile.png`, fullPage: true});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({width: 1600, height: 1000});
  await page.getByRole('link', {name: '回到校园', exact: true}).click();
  await expect(page.getByRole('button', {name: '以 Visitor 身份进入'})).toBeEnabled({timeout: 90000});
  await page.getByLabel('旅途中，怎么称呼你？').fill('角色测试');
  await page.getByRole('button', {name: '以 Visitor 身份进入'}).click();
  const before = await page.evaluate(() => window.__worldScene.position);
  await page.keyboard.down('w');
  await page.waitForTimeout(1800);
  await page.keyboard.up('w');
  const after = await page.evaluate(() => window.__worldScene.position);
  expect(Math.hypot(after[0] - before[0], after[2] - before[2])).toBeGreaterThan(2);
  await page.screenshot({path: `${directory}/campus.png`});
  await expect(page.getByRole('link', {name: '人物预览', exact: true})).toBeVisible();
  expect(errors).toEqual([]);
  expect(failures).toEqual([]);
  const report = {errors, failures, movementMetres: Math.hypot(after[0] - before[0], after[2] - before[2]), scene: await page.evaluate(() => window.__worldScene)};
  await writeFile(`${directory}/report.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally {await browser.close();}
